import { chromium } from '../../../../src/node_modules/playwright/index.mjs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const browser = await chromium.launch({headless:true});
let checks = 0;
function check(ok, name) { if (!ok) throw new Error(name); checks++; }
try {
 for (const width of [320,390,768,1440]) {
  const page = await browser.newPage({viewport:{width,height:900}});
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve('docs/ux/03-screens/vendas/master.html')).href);
  await page.locator('[data-screen="lancamentos"]').click();
  await page.locator('[data-launch-screen="saidas"]').click();
  const output = page.locator('.output-workspace');
  check(await output.isVisible(), 'abre em lançamentos');
  check(await output.locator('.output-record').count() === 6, 'seis exemplos iniciais');
  check(await output.locator('.output-stat').count() === 0, 'cards por motivo removidos');
  check((await output.locator('[data-output-net]').textContent()).includes('252,00') && (await output.locator('[data-output-net]').textContent()).includes('parcial'), 'custo líquido conhecido com pendência explícita');
  check((await output.locator('[data-output-gross]').textContent()).includes('283,00'), 'custo bruto inclui estornos');
  check((await output.locator('[data-output-reversed-total]').textContent()).includes('31,00'), 'custo estornado correto');
  await output.locator('[data-output-expand="1"]').click();
  await output.locator('[data-output-expand="2"]').click();
  check(await output.locator('.output-expanded-row:not([hidden])').count() === 2, 'vários detalhes simultâneos');
  const detailBox = await output.locator('#output-detail-1').boundingBox();
  const tableBox = await output.locator('.output-table').boundingBox();
  check(detailBox.width >= tableBox.width * .95, 'detalhe ocupa largura da tabela');
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'detalhe aberto sem overflow');
  await output.locator('[data-output-expand="3"]').click();
  check((await output.locator('#output-detail-3 [data-output-open-cost]').textContent()).includes('Informar custo'), 'custo ausente oferece preenchimento');
  await output.locator('#output-detail-3 [data-output-open-cost]').click();
  check(await output.locator('.output-cost-dialog').evaluate(dialog => dialog.open), 'abre edição de custo pelo histórico');
  check(await output.locator('[data-output-history-cost-index="0"]').inputValue() === '', 'histórico não inventa custo ausente');
  await output.locator('[data-output-history-cost-index="0"]').fill('27.50');
  await output.getByRole('button', { name: 'Salvar custos', exact: true }).click();
  check((await output.locator('[data-record-id="3"]').textContent()).includes('27,50'), 'custo salvo aparece na linha');
  check((await output.locator('#output-detail-3 [data-output-open-cost]').textContent()).includes('Editar custo'), 'custo conhecido pode ser corrigido');
  check((await output.locator('[data-output-net]').textContent()).includes('279,50'), 'resumo recalcula após custo histórico');
  check(await output.locator('.output-missing-cost').count() === 0, 'pendência de custo desaparece');
  await output.locator('[data-output-search]').fill('220018-16');
  await output.locator('[data-output-add="220018-16"]').click();
  check(await output.locator('[data-output-cost]').inputValue() === '', 'custo ausente fica vazio');
  check((await output.locator('[data-output-item-cost]').textContent()).includes('Não informado'), 'ausência não é zero');
  await output.locator('[data-output-cost]').fill('0');
  check((await output.locator('[data-output-item-cost]').textContent()).includes('0,00'), 'zero explícito é custo conhecido');
  await output.locator('[data-output-cost]').fill('12.34');
  await output.locator('[data-output-change][data-delta="1"]').click();
  check((await output.locator('[data-output-item-cost]').textContent()).includes('24,68'), 'custo multiplica quantidade em centavos');
  await output.locator('[data-output-remove]').click();
  check(await output.locator('.is-reversed').count() === 1, 'exemplo estornado');
  check(await page.locator('.today-sales').isHidden(), 'histórico comercial oculto');
  await output.locator('[data-output-search]').fill('anel');
  check(await output.locator('[data-output-add]').count() === 2, 'variações explícitas');
  await output.locator('[data-output-add="220018-18"]').click();
  check(await output.locator('[data-output-change][data-delta="1"]').isDisabled(), 'limite de saldo');
  check(await output.locator('[data-output-cost]').inputValue() === '31.00', 'custo do cadastro pré-preenchido');
  await output.locator('[data-output-cost]').fill('12.34');
  await output.locator('[name="reason"]').selectOption('Sorteio');
  await output.locator('[name="destination"]').fill('Campanha <primavera>');
  await output.getByRole('button',{name:'Revisar saída',exact:true}).click();
  check(!await output.locator('.output-dialog').first().evaluate(el=>el.open), 'explicação obrigatória');
  await output.locator('[name="note"]').fill('Prêmio da campanha');
  await page.locator('[data-launch-type="sale"]').click();
  check(await output.isHidden(), 'troca para venda');
  await page.locator('[data-launch-screen="saidas"]').click();
  check(await output.locator('[name="note"]').inputValue() === 'Prêmio da campanha', 'rascunho preservado');
  await output.getByRole('button',{name:'Revisar saída',exact:true}).click();
  check((await output.locator('[data-output-review]').textContent()).includes('Campanha <primavera>'), 'destino escapado na revisão');
  await output.getByRole('button',{name:'Voltar e editar'}).click();
  await output.getByRole('button',{name:'Revisar saída',exact:true}).click();
  await output.locator('[data-output-confirm]').click();
  check(await output.locator('.output-record').count() === 7, 'registro único');
  check((await output.locator('[data-output-feedback]').textContent()).includes('Nenhum dado real'), 'simulação declarada');
check((await output.locator('[data-record-id="7"]').textContent()).includes('12,34'), 'custo confirmado preservado no histórico');
  check((await output.locator('[data-output-net]').textContent()).includes('291,84'), 'novo custo soma ao líquido');
  await output.locator('[data-output-expand="7"]').click();
  await output.locator('#output-detail-7 [data-output-reverse]').click();
  await output.locator('[name="explanation"]').fill('Lançado por engano');
  await output.getByRole('button',{name:'Confirmar estorno'}).click();
  check((await output.locator('.output-record').first().textContent()).includes('Estornada'), 'original estornado e preservado');
  check(await output.locator('#output-detail-7 [data-output-reverse]').count() === 0, 'sem segundo estorno');
  await output.locator('[data-output-search]').fill('220018-18');
  check(await output.locator('[data-output-add]').isEnabled(), 'saldo restaurado');
  check((await output.locator('[data-output-net]').textContent()).includes('279,50'), 'estorno restaura custo líquido');
  await output.locator('[data-output-add]').click();
  check(await output.locator('[data-output-cost]').inputValue() === '31.00', 'custo original do cadastro preservado');
  await output.locator('[data-output-remove]').click();
  await output.locator('[data-output-state]').selectOption('reversed');
  check(await output.locator('.output-record').count() === 2, 'filtro de estornos');
  await output.locator('[data-output-state]').selectOption('');
  await output.locator('[data-output-period="7d"]').click();
  check(await output.locator('[data-output-period="7d"]').evaluate(button => button.classList.contains('active')), 'atalho de período ativo');
  check(await output.locator('.output-record').count() === 7, 'atalho de sete dias preserva registros do dia');
  await output.locator('[data-output-period="all"]').click();
  await output.locator('[data-output-filter]').selectOption('Brinde');
  check(await output.locator('.output-record').count() === 2, 'filtro');
  await output.locator('[data-output-filter]').selectOption('');
  check(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), `sem overflow ${width}`);
  check(errors.length === 0, errors.join('\n'));
  await page.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0,0); });
  if (width===390 || width===1440) await page.screenshot({path:`docs/ux/03-screens/vendas/output-${width}.png`,fullPage:true});
  await page.close();
 }
 console.log(`${checks} verificações aprovadas`);
} finally { await browser.close(); }
